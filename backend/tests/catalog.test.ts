import 'dotenv/config';
import { test,after } from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import { randomUUID } from 'node:crypto';
import { db } from '../src/config/database.js';
import { createApp } from '../src/app.js';
import { hashPassword } from '../src/utils/security.js';
const origin='http://localhost:5173';
if(!process.env.TEST_DATABASE_URL||process.env.DATABASE_URL!==process.env.TEST_DATABASE_URL)throw new Error('Use an isolated migrated test database.');
const app=createApp(origin), tag=randomUUID(), email=tag+'@example.invalid', password='Long integration password 123';
const admin=request.agent(app);
const post=(path:string,body:unknown)=>admin.post(path).set('Origin',origin).send(body);
const patch=(path:string,body:unknown)=>admin.patch(path).set('Origin',origin).send(body);
after(async()=>{await db.product.deleteMany({where:{slug:tag}});await db.category.deleteMany({where:{slug:tag}});await db.brand.deleteMany({where:{slug:tag}});await db.user.deleteMany({where:{email}});await db.$disconnect();});
test('catalog publication, filters, inventory and admin authorization',async()=>{
 await db.user.create({data:{email,name:'Test admin',mobile:'9999999999',passwordHash:await hashPassword(password),termsAcceptedAt:new Date(),role:'ADMIN'}});
 await request(app).post('/api/admin/catalog/categories').set('Origin',origin).send({name:'Test',slug:tag}).expect(401);
 await post('/api/auth/login',{email,password}).expect(200);
 const category=(await post('/api/admin/catalog/categories',{name:'Test category',slug:tag}).expect(201)).body;
 const brand=(await post('/api/admin/catalog/brands',{name:'Test brand',slug:tag}).expect(201)).body;
 const body={name:'Test Linen Shirt',slug:tag,description:'Test fixture only',pricePaise:149900,categoryId:category.id,brandId:brand.id,images:[{url:'https://example.invalid/test.jpg',alt:'Test fixture'}],variants:[{sku:tag+'-m',size:'M',color:'Ivory',stock:2},{sku:tag+'-l',size:'L',color:'Black',stock:0}]};
 const product=(await post('/api/admin/catalog/products',body).expect(201)).body;
 await request(app).get('/api/products/'+tag).expect(404);
 await patch('/api/admin/catalog/products/'+product.id,{published:true}).expect(200);
 const detail=(await request(app).get('/api/products/'+tag).expect(200)).body;
 assert.equal(detail.pricePaise,149900);assert.equal(detail.variants.length,2);assert.equal(detail.variants[0].stock,undefined);
 const list=(await request(app).get('/api/products').query({category:tag,q:'linen',size:'M',color:'Ivory',inStock:'true',minPrice:100000,maxPrice:200000}).expect(200)).body;
 assert.equal(list.total,1);
 const mismatched=(await request(app).get('/api/products').query({category:tag,size:'M',color:'Black'}).expect(200)).body;assert.equal(mismatched.total,0);
 const m=product.variants.find((v:{size:string})=>v.size==='M');
 await patch('/api/admin/catalog/variants/'+m.id+'/stock',{stock:0}).expect(200);
 const empty=(await request(app).get('/api/products').query({category:tag,inStock:'true'}).expect(200)).body;assert.equal(empty.total,0);
 await patch('/api/admin/catalog/products/'+product.id,{published:false}).expect(200);
 await request(app).get('/api/products/'+tag).expect(404);
});
