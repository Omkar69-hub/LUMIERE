import 'dotenv/config';
import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import {randomUUID} from 'node:crypto';
import {db} from '../src/config/database.js';
import {createApp} from '../src/app.js';
import {hashPassword} from '../src/utils/security.js';
const origin='http://localhost:5173';
if(!process.env.TEST_DATABASE_URL||process.env.DATABASE_URL!==process.env.TEST_DATABASE_URL)throw new Error('Use an isolated test database.');
const tag=randomUUID(),emails=[tag+'-admin@example.invalid',tag+'-customer@example.invalid'],password='Admin integration password 123';
const app=createApp(origin),admin=request.agent(app),customer=request.agent(app);
const patch=(path:string,body:unknown)=>admin.patch(path).set('Origin',origin).send(body);
after(async()=>{await db.adminEvent.deleteMany({where:{actor:{email:emails[0]}}});await db.order.deleteMany({where:{user:{email:emails[1]}}});await db.user.deleteMany({where:{email:{in:emails}}});await db.$disconnect();});
test('admin authorization, customer suspension and safe fulfillment',async()=>{
 const hash=await hashPassword(password);
 const [a,c]=await Promise.all(emails.map((email,i)=>db.user.create({data:{email,name:'Test account',mobile:'9999999999',passwordHash:hash,termsAcceptedAt:new Date(),role:i===0?'ADMIN':'CUSTOMER'}})));
 const login=(agent:typeof admin,email:string)=>agent.post('/api/auth/login').set('Origin',origin).send({email,password});
 await request(app).get('/api/admin/overview').expect(401);
 await login(customer,c.email).expect(200);
 for(const route of ['/overview','/customers','/orders','/events','/catalog/categories'])await customer.get('/api/admin'+route).expect(403);
 await login(admin,a.email).expect(200);
 const overview=(await admin.get('/api/admin/overview').expect(200)).body;assert.equal(overview.testMode,true);assert.equal(typeof overview.revenuePaise,'number');assert.equal(typeof overview.availableStock,'number');assert.equal(typeof overview.openSupport,'number');assert.ok(Array.isArray(overview.recent));assert.ok(Array.isArray(overview.alerts));
 const list=(await admin.get('/api/admin/customers').query({q:tag}).expect(200)).body;assert.equal(list.items.length,1);assert.equal(list.items[0].passwordHash,undefined);
 await patch('/api/admin/customers/'+a.id+'/status',{suspended:true}).expect(404);
 await admin.patch('/api/admin/customers/'+c.id+'/status').send({suspended:true}).expect(403);
 await patch('/api/admin/customers/'+c.id+'/status',{suspended:true}).expect(200);
 await customer.get('/api/users/me').expect(401);await login(customer,c.email).expect(401);
 await patch('/api/admin/customers/'+c.id+'/status',{suspended:false}).expect(200);await login(customer,c.email).expect(200);
 const o=await db.order.create({data:{userId:c.id,requestKey:tag,addressSnapshot:{recipient:'Test'},subtotalPaise:1000,shippingPaise:0,totalPaise:1000}});
 await patch('/api/admin/orders/'+o.id+'/fulfillment',{status:'PACKING'}).expect(409);
 await patch('/api/admin/orders/'+o.id+'/fulfillment',{status:'PAID'}).expect(400);
 await db.order.update({where:{id:o.id},data:{status:'PAID',paidAt:new Date()}});
 await patch('/api/admin/orders/'+o.id+'/fulfillment',{status:'SHIPPED',carrier:'Test',trackingNumber:'123'}).expect(409);
 await patch('/api/admin/orders/'+o.id+'/fulfillment',{status:'PACKING'}).expect(200);
 await patch('/api/admin/orders/'+o.id+'/fulfillment',{status:'SHIPPED'}).expect(400);
 await patch('/api/admin/orders/'+o.id+'/fulfillment',{status:'SHIPPED',carrier:'Test carrier',trackingNumber:'123'}).expect(200);
 await patch('/api/admin/orders/'+o.id+'/fulfillment',{status:'OUT_FOR_DELIVERY'}).expect(200);
 await patch('/api/admin/orders/'+o.id+'/fulfillment',{status:'DELIVERED'}).expect(200);
 assert.equal((await customer.get('/api/orders/'+o.id).expect(200)).body.fulfillment,'DELIVERED');
 const events=(await admin.get('/api/admin/events').expect(200)).body.items;assert.ok(events.some((e:{targetId:string;action:string})=>e.targetId===o.id&&e.action==='FULFILLMENT_DELIVERED'));
 await admin.post('/api/admin/orders/'+o.id+'/cancel').set('Origin',origin).send({}).expect(409);
});
