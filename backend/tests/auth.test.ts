import 'dotenv/config';
import { test,after } from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import { randomUUID } from 'node:crypto';
import { db } from '../src/config/database.js';
import { createApp } from '../src/app.js';
const origin='http://localhost:5173';
if(!process.env.TEST_DATABASE_URL||process.env.DATABASE_URL!==process.env.TEST_DATABASE_URL)throw new Error('Use an isolated migrated test database: DATABASE_URL must equal TEST_DATABASE_URL.');
const delivered:{purpose:string;url:string}[]=[];
const app=createApp(origin,async(_email,purpose,url)=>{delivered.push({purpose,url});});
const email='test-'+randomUUID()+'@example.invalid';
const password='A long test password 123';
const nextPassword='Another long test password 456';
const agent=request.agent(app);
const post=(path:string,body:unknown)=>agent.post(path).set('Origin',origin).send(body);
after(async()=>{await db.user.deleteMany({where:{email}});await db.$disconnect();});
test('database-backed authentication, recovery and access controls',async()=>{
 const reg=await post('/api/auth/register',{name:'Test Customer',email,mobile:'9999999999',password,confirmPassword:password,terms:true}).expect(201);
 assert.equal(reg.body.user.email,email);assert.equal(reg.body.user.passwordHash,undefined);
 assert.match(String(reg.headers['set-cookie']),/HttpOnly/i);
 const user=await db.user.findUniqueOrThrow({where:{email}});assert.match(user.passwordHash,/^\$argon2id\$/);
 await post('/api/auth/register',{name:'Test Customer',email,mobile:'9999999999',password,confirmPassword:password,terms:true}).expect(409);
 await agent.patch('/api/users/me').send({name:'Bad origin'}).expect(403);
 await agent.patch('/api/users/me').set('Origin',origin).send({name:'Updated Customer'}).expect(200);
 await agent.post('/api/addresses').set('Origin',origin).send({recipient:'Test Customer',line1:'Test street',city:'Pune',state:'Maharashtra',postalCode:'411001'}).expect(201);
 await agent.get('/api/admin/access').expect(403);
 const verify=new URL(delivered.find(x=>x.purpose==='VERIFY_EMAIL')!.url).hash.slice(7);
 await post('/api/auth/verify-email',{token:verify}).expect(200);
 await post('/api/auth/verify-email',{token:verify}).expect(400);
 await post('/api/auth/logout',{}).expect(204);
 await agent.get('/api/users/me').expect(401);
 await post('/api/auth/login',{email,password:'wrong password'}).expect(401);
 await post('/api/auth/login',{email,password,remember:true}).expect(200);
 const profile=await agent.get('/api/users/me').expect(200);assert.equal(profile.body.user.name,'Updated Customer');
 const addresses=await agent.get('/api/addresses').expect(200);assert.equal(addresses.body.length,1);
 await post('/api/auth/forgot-password',{email}).expect(202);
 const reset=new URL(delivered.find(x=>x.purpose==='RESET_PASSWORD')!.url).hash.slice(7);
 await post('/api/auth/reset-password',{token:reset,password:nextPassword,confirmPassword:nextPassword}).expect(200);
 await agent.get('/api/users/me').expect(401);
 await post('/api/auth/reset-password',{token:reset,password:password,confirmPassword:password}).expect(400);
 await post('/api/auth/login',{email,password}).expect(401);
 await post('/api/auth/login',{email,password:nextPassword}).expect(200);
});
