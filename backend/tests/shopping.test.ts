import 'dotenv/config';
import { test,after } from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import { randomUUID } from 'node:crypto';
import { db } from '../src/config/database.js';
import { createApp } from '../src/app.js';
const origin='http://localhost:5173';
if(!process.env.TEST_DATABASE_URL||process.env.DATABASE_URL!==process.env.TEST_DATABASE_URL)throw new Error('Use an isolated migrated test database.');
const app=createApp(origin),tag=randomUUID(),password='Shopping test password 123';
const emails=[tag+'-a@example.invalid',tag+'-b@example.invalid'];
const a=request.agent(app),b=request.agent(app);
const signup=(agent:typeof a,email:string)=>agent.post('/api/auth/register').set('Origin',origin).send({name:'Test buyer',email,mobile:'9999999999',password,confirmPassword:password,terms:true});
after(async()=>{await db.user.deleteMany({where:{email:{in:emails}}});await db.product.deleteMany({where:{slug:tag}});await db.category.deleteMany({where:{slug:tag}});await db.brand.deleteMany({where:{slug:tag}});await db.$disconnect();});
test('persistent cart, wishlist, inventory and account isolation',async()=>{
 const category=await db.category.create({data:{slug:tag,name:'Test category'}}),brand=await db.brand.create({data:{slug:tag,name:'Test brand'}});
 const p=await db.product.create({data:{slug:tag,name:'Test coat',description:'Test only',pricePaise:250000,published:true,categoryId:category.id,brandId:brand.id,variants:{create:{sku:tag,size:'M',color:'Sand',stock:3}}},include:{variants:true}});
 const variantId=p.variants[0].id;
 await request(app).get('/api/cart').expect(401);
 await signup(a,emails[0]).expect(201);await signup(b,emails[1]).expect(201);
 await a.put('/api/cart/items').send({variantId,quantity:1}).expect(403);
 await a.put('/api/cart/items').set('Origin',origin).send({variantId,quantity:4}).expect(409);
 await a.put('/api/cart/items').set('Origin',origin).send({variantId,quantity:1,pricePaise:1}).expect(400);
 const item=(await a.put('/api/cart/items').set('Origin',origin).send({variantId,quantity:2}).expect(200)).body;
 await a.put('/api/cart/items').set('Origin',origin).send({variantId,quantity:2}).expect(200);
 const first=(await a.get('/api/cart').expect(200)).body;assert.equal(first.items.length,1);assert.equal(first.subtotalPaise,500000);
 await b.patch('/api/cart/items/'+item.id).set('Origin',origin).send({quantity:1}).expect(404);
 await b.delete('/api/cart/items/'+item.id).set('Origin',origin).expect(404);
 assert.equal((await b.get('/api/cart').expect(200)).body.items.length,0);
 await a.put('/api/wishlist/items/'+p.id).set('Origin',origin).expect(204);
 await a.put('/api/wishlist/items/'+p.id).set('Origin',origin).expect(204);
 await b.delete('/api/wishlist/items/'+p.id).set('Origin',origin).expect(204);
 assert.equal((await b.get('/api/wishlist').expect(200)).body.length,0);
 await a.post('/api/auth/logout').set('Origin',origin).send({}).expect(204);
 await a.get('/api/wishlist').expect(401);
 await a.post('/api/auth/login').set('Origin',origin).send({email:emails[0],password}).expect(200);
 assert.equal((await a.get('/api/wishlist').expect(200)).body.length,1);
 assert.equal((await a.get('/api/cart').expect(200)).body.items[0].quantity,2);
 await db.productVariant.update({where:{id:variantId},data:{stock:1}});
 const unavailable=(await a.get('/api/cart').expect(200)).body;assert.equal(unavailable.allAvailable,false);assert.equal(unavailable.subtotalPaise,0);
 await a.patch('/api/cart/items/'+item.id).set('Origin',origin).send({quantity:1}).expect(200);
 assert.equal((await a.get('/api/cart').expect(200)).body.subtotalPaise,250000);
 await a.delete('/api/cart/items/'+item.id).set('Origin',origin).expect(204);
 await a.delete('/api/wishlist/items/'+p.id).set('Origin',origin).expect(204);
 assert.equal((await a.get('/api/cart').expect(200)).body.items.length,0);
 assert.equal((await a.get('/api/wishlist').expect(200)).body.length,0);
});
