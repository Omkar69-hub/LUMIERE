import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
test('register, sign out, sign in, persist and protect account',async({page})=>{
 const email=randomUUID()+'@example.invalid',password='Browser test password 123';
 await page.goto('/signup');
 await expect(page.getByRole('heading',{name:'Create your account'})).toBeVisible();
 await page.getByLabel('Full name').fill('Browser Customer');
 await page.getByLabel('Mobile number').fill('9999999999');
 await page.getByLabel('Email address').fill(email);
 await page.getByLabel('Password',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Show password',exact:true}).click();
 await expect(page.getByLabel('Password',{exact:true})).toHaveAttribute('type','text');
 await page.getByRole('button',{name:'Hide password',exact:true}).click();
 await page.getByLabel('Confirm password',{exact:true}).fill(password+'wrong');
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'Create account'}).click();
 await expect(page.getByRole('alert')).toContainText('Please confirm');
 await page.getByLabel('Confirm password',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Create account'}).click();
 await expect(page).toHaveURL(/\/account$/);
 await expect(page.getByRole('heading',{name:'Welcome, Browser Customer.'})).toBeVisible();
 await page.getByLabel('Name',{exact:true}).fill('Updated Browser Customer');
 await page.getByRole('button',{name:'Save profile'}).click();
 await expect(page.getByRole('status')).toContainText('Profile saved');
 await page.reload();
 await expect(page.getByRole('heading',{name:'Welcome, Updated Browser Customer.'})).toBeVisible();
 await page.getByRole('button',{name:'Sign out'}).click();
 await expect(page).toHaveURL(/\/login$/);
 await page.goto('/account');await expect(page).toHaveURL(/\/login$/);
 await page.getByLabel('Email address').fill(email);
 await page.getByLabel('Password',{exact:true}).fill('wrong password');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('Invalid email or password');
 await page.getByLabel('Password',{exact:true}).fill(password);
 await page.getByLabel('Remember me').check();
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page).toHaveURL(/\/account$/);
 await expect(page.getByRole('heading',{name:'Welcome, Updated Browser Customer.'})).toBeVisible();
 await page.goto('/admin');await expect(page.getByRole('heading',{name:'Access denied'})).toBeVisible();
});
test('reduced motion and navigable search overlay',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto('/');
 await page.getByRole('button',{name:'Search',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByLabel('Search the collection').fill('linen');
 await page.getByRole('button',{name:'Explore results'}).click();
 await expect(page).toHaveURL(/\/shop\?q=linen/);
 await page.goto('/login');
 await expect(page.getByLabel('Email address')).toBeVisible();
 await page.getByLabel('Email address').focus();await expect(page.getByLabel('Email address')).toBeFocused();
 await page.keyboard.press('Tab');await expect(page.getByLabel('Password',{exact:true})).toBeFocused();
});

test('public catalogue navigation, filters and policy access',async({page,isMobile})=>{
 await page.goto('/');
 await page.getByRole('link',{name:'Explore the collection'}).click();
 await expect(page).toHaveURL(/\/shop$/);
 if(isMobile)await page.getByRole('button',{name:'Filter & sort'}).click();
 await page.getByRole('textbox',{name:'Search',exact:true}).fill('linen');
 await page.getByRole('button',{name:'Apply filters'}).click();
 await expect(page).toHaveURL(/\/shop\?q=linen/);
 await page.goto('/shipping');await expect(page.getByRole('heading',{name:'Shipping policy — draft'})).toBeVisible();
 await page.goto('/support');await expect(page.getByRole('link',{name:'Sign in to contact support'})).toBeVisible();
});
